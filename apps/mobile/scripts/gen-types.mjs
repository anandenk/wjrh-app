// Generates src/api/types.ts from backend/schemas/*.schema.json (the API contract).
// Run: npm run gen:types   (re-run whenever backend/schemas changes; commit the result)
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';

const here = dirname(fileURLToPath(import.meta.url));
const schemaDir = join(here, '../../../backend/schemas');
const out = join(here, '../src/api/types.ts');

// "now-playing.schema.json" -> "NowPlaying"
const typeName = (file) =>
  file.startsWith('error.') // not "Error": that would shadow the built-in
    ? 'ApiErrorBody'
    : file
    .replace('.schema.json', '')
    .split('-')
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join('');

let body = `/* eslint-disable */
// GENERATED by scripts/gen-types.mjs from backend/schemas/*.schema.json. Do not edit by hand.
// Source of truth for these shapes is the schemas; the API's tests validate against the same files.
`;

const hash = createHash('sha256');

for (const file of readdirSync(schemaDir).filter((f) => f.endsWith('.schema.json')).sort()) {
  const raw = readFileSync(join(schemaDir, file), 'utf8');
  hash.update(file).update(raw);
  const schema = JSON.parse(raw);
  delete schema.title; // otherwise title/$id ("/v1 now-playing") would name the type
  delete schema.$id;
  const ts = await compile(schema, typeName(file), {
    bannerComment: '',
    additionalProperties: false,
    format: true,
  });
  body += `\n// ${file}\n${ts}`;
}

writeFileSync(out, body);
console.log(`wrote ${out}`);

// The saved API answers on the phone (src/api/cache-rules.ts) are thrown away when this changes, so an
// app update that changes a response shape never reads old data in the new shape.
const versionOut = join(here, '../src/api/schema-version.ts');
writeFileSync(
  versionOut,
  `// GENERATED by scripts/gen-types.mjs from backend/schemas/*.schema.json. Do not edit by hand.
// A hash of every schema file. The saved-answers cache is keyed on it (src/api/cache-rules.ts).
export const SCHEMA_VERSION = '${hash.digest('hex').slice(0, 12)}';
`,
);
console.log(`wrote ${versionOut}`);
